"""Schema-level enforcement of docs/ip-safety.md constraint 7.

"Scraped data from AI engines or competitor pages is for FACTS ONLY... Never
store, render, or republish a competitor's actual copyrighted text."

These tests make that a build failure rather than a review comment. If someone
adds a `raw_response` column to EngineResult in eighteen months, CI stops them.
"""

from __future__ import annotations

import pytest
from sqlalchemy import String, Text

from avp_api.models import (
    Base,
    BrandMention,
    Citation,
    Client,
    Competitor,
    EngineResult,
    TechnicalAudit,
    TechnicalAuditCheck,
)

# Tables holding data derived from third-party sources (AI engine answers,
# competitor pages). These may hold facts only.
FACTS_ONLY_MODELS = [
    EngineResult,
    Citation,
    BrandMention,
    Competitor,
    TechnicalAudit,
    TechnicalAuditCheck,
    # Added in Epic 2. The intake crawl fetches a prospect's pages, so Client
    # is now downstream of third-party content and must obey the same rule:
    # what it stores is the CONCLUSION (industry label, niche, brand name,
    # confidence), never the page copy that led to it.
    Client,
]

# Column names that would indicate raw third-party content is being stored.
FORBIDDEN_COLUMN_NAMES = {
    "raw_response", "response", "response_text", "answer", "answer_text",
    "body", "content", "text", "raw", "raw_html", "html", "markdown",
    "snippet", "excerpt", "quote", "summary", "description", "context",
    "title", "headline", "meta_description", "copy", "page_text",
    "completion", "output", "message",
}

# Long free-text columns are how raw content gets stored in practice. Facts are
# short and bounded: a domain is <=253, an entity name <=200.
MAX_STRING_LENGTH_FOR_FACTS = 2048


@pytest.mark.parametrize("model", FACTS_ONLY_MODELS, ids=lambda m: m.__tablename__)
def test_no_column_named_like_raw_content(model: type[Base]) -> None:
    offending = {
        c.name for c in model.__table__.columns if c.name.lower() in FORBIDDEN_COLUMN_NAMES
    }
    assert not offending, (
        f"{model.__tablename__} has column(s) {sorted(offending)} whose names indicate "
        f"raw third-party content. ip-safety.md #7 permits facts only: booleans, "
        f"counts, ordinals, domains, URLs, entity names, and structural signals. "
        f"If a feature seems to need the raw text, STOP and flag it."
    )


@pytest.mark.parametrize("model", FACTS_ONLY_MODELS, ids=lambda m: m.__tablename__)
def test_no_unbounded_text_columns(model: type[Base]) -> None:
    """A TEXT column is an open invitation to paste an answer into it."""
    offending = []
    for column in model.__table__.columns:
        type_ = column.type
        if isinstance(type_, Text):
            offending.append(f"{column.name} (TEXT)")
        elif isinstance(type_, String) and (type_.length or 10**9) > MAX_STRING_LENGTH_FOR_FACTS:
            offending.append(f"{column.name} (VARCHAR({type_.length}))")
    assert not offending, (
        f"{model.__tablename__} has unbounded/oversized text column(s) {offending}. "
        f"Facts are short and bounded. See ip-safety.md #7."
    )


