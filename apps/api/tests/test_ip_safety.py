def test_the_fix_prompt_carries_no_line_that_is_not_a_whitelisted_fact() -> None:
    """Every line of the built prompt must match a known fact label.

    The categorical form of the guard, and the one Epic 5.1 argues for: a
    canary test catches the canary, whereas this catches the class. Adding an
    interpolation that carries page copy, a citation title or a competitor
    description means adding a line whose label is not below — which fails here
    rather than shipping.
    """
    from decimal import Decimal

    from avp_api.services.fix_generator import (
        DimensionFact,
        FixFacts,
        build_candidates,
        build_fix_prompt,
    )

    allowed_prefixes = (
        "Subject brand:", "Website:", "Industry (classified automatically",
        "Niche:", "Visibility score:", "Measurement caveats:",
        "Dimension scores (", "Competitors detected,", "Answer coverage:",
        "Citation coverage:", "Most-cited domains:", "Site structure signals:",
        "Write one fix for each",
    )

    facts = FixFacts(
        domain="helpscout.com",
        brand_name="Help Scout",
        industry="customer support software",
        niche="shared inbox",
        composite=Decimal("58.24"),
        formula_version="v1.1",
        degradation_flags=["NO_AUTHORITY_DATA"],
        dimensions=[
            DimensionFact(
                key="citation_strength",
                weight=Decimal("20.00"),
                subscore=Decimal("3.70"),
                gap=Decimal("19.26"),
            )
        ],
        competitor_names=[("Zendesk", "zendesk.com")],
        answers_analysed=6,
        answers_naming_subject=6,
        citations_total=45,
        citations_to_subject=3,
        top_cited_domains=[("eesel.ai", 6)],
        schema_types=["Corporation", "WebSite"],
        word_count=877,
        h1_count=1,
        indexable=True,
        has_sitemap=True,
    )
    # Every field must carry a value. A second negative control proved why: a
    # line emitted only `if facts.competitor_description` is invisible to this
    # sweep when the field defaults to None, so the guard would have inspected
    # a prompt the injected branch never reached. Asserting over
    # dataclasses.fields means a newly added field fails HERE, unset, rather
    # than passing unexamined.
    import dataclasses

    unset = [
        f.name for f in dataclasses.fields(facts) if getattr(facts, f.name) in (None, [], "")
    ]
    assert not unset, f"give {unset} a value — an unset field hides its prompt line"

    candidates = build_candidates(
        facts.dimensions, [("schema_faq", "warn", "NO_FAQ_SCHEMA")]
    )
    lines = [line for line in build_fix_prompt(facts, candidates).splitlines() if line.strip()]

    # A sweep that covers nothing passes vacuously (Epic 7's `checked >= 10`).
    assert len(lines) >= 14, f"only {len(lines)} lines — the prompt did not build"

    for line in lines:
        if line.startswith("- "):
            continue  # list items under a whitelisted heading
        assert line.startswith(allowed_prefixes), f"unwhitelisted prompt line: {line!r}"


def test_the_facts_bundle_has_no_field_that_could_hold_prose() -> None:
    """`FixFacts` is where a leak would have to land to reach the prompt.

    A dataclasses.fields() name sweep, the same shape as Epic 6's
    `test_signals_carry_no_page_content`. Enforced by the type, so a future
    edit that adds `competitor_description` fails here before it can be
    interpolated anywhere.
    """
    import dataclasses

    from avp_api.services.fix_generator import FixFacts

    names = {f.name for f in dataclasses.fields(FixFacts)}
    forbidden = (
        "text", "answer", "response", "snippet", "excerpt", "quote", "body",
        "content", "html", "raw", "description", "tagline", "summary",
        "positioning", "about", "title", "headline", "copy", "prose", "blurb",
    )
    # Matched as a SUBSTRING of the field name, not by exact equality. A
    # negative control proved why: `competitor_description` passes an exact-set
    # sweep containing "description" without difficulty, and a leak field will
    # always be named for what it holds plus a qualifier. Recorded in
    # docs/build-log.md under Epic 8's negative controls.
    # A field may only carry a forbidden word if its TYPE cannot hold prose.
    # `answers_analysed` and `answers_naming_subject` are ints — they count
    # engine answers rather than holding one. Keying the exemption on the
    # annotation rather than on a name allowlist means `answer_excerpt: str`
    # cannot be waved through the same way.
    countable = {"int", "bool", "Decimal"}
    leaks = sorted(
        f.name
        for f in dataclasses.fields(FixFacts)
        if any(word in f.name for word in forbidden)
        and not any(t in str(f.type) for t in countable)
    )
    assert not leaks, f"FixFacts.{leaks} could carry third-party prose"
    assert len(names) >= 15, "the sweep must actually cover the bundle"


