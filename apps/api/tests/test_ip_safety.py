def test_only_dates_are_taken_from_json_ld() -> None:
    """JSON-LD carries headlines, author names and article bodies.

    The freshness extractor must read datePublished/dateModified and nothing
    else — a regex over the whole blob that happened to capture text would be a
    quiet violation.
    """
    from avp_api.services.technical_audit import _extract_structured_date

    blob = (
        '{"@type":"Article","headline":"SECRET HEADLINE TEXT",'
        '"articleBody":"SECRET BODY COPY","datePublished":"2026-01-15"}'
    )
    result = _extract_structured_date(blob)
    assert result is not None
    assert result.year == 2026 and result.month == 1 and result.day == 15
    assert "SECRET" not in str(result)


