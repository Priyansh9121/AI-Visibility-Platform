// --- report (Epic 7) ------------------------------------------------------
// The report is the first surface that RENDERS collected facts. These tests
// guard the wire contract the report screen is built against.

const report = spec.components.schemas.ReportOut.properties;

test('the report endpoint is present', () => {
  assert.ok(spec.paths['/api/v1/scans/{scanId}/report']);
});

test('the report carries all five beats worth of material', () => {
  for (const field of ['score', 'dimensions', 'competitorSet', 'proof', 'audit']) {
    assert.ok(report[field], `ReportOut.${field} is missing`);
  }
});

test('score, competitorSet and audit are nullable so degraded scans are representable', () => {
  // A scan that was never scored, never had competitors detected, or was never
  // audited must be renderable as such — not as a zero and not as a crash.
  for (const field of ['score', 'competitorSet', 'audit']) {
    const schema = JSON.stringify(report[field]);
    assert.match(schema, /"type":"null"/, `ReportOut.${field} must be nullable`);
  }
});

test('a report dimension can be excluded without being a zero', () => {
  const dimension = spec.components.schemas.ReportDimensionOut.properties;
  assert.ok(dimension.included);
  assert.ok(dimension.exclusionReason);
  // subscore is nullable: an excluded dimension has no value, which is a
  // different claim from a measured zero.
  assert.match(JSON.stringify(dimension.subscore), /"type":"null"/);
});

test('report decimals are string-encoded, never JSON numbers', () => {
  const dimension = spec.components.schemas.ReportDimensionOut.properties;
  assert.match(JSON.stringify(dimension.weight), /"type":"string"/);
  assert.match(JSON.stringify(dimension.subscore), /"type":"string"/);
});

test('report competitors carry identity and comparable sub-scores, no composite', () => {
  const competitor = spec.components.schemas.ReportCompetitorOut.properties;
  assert.ok(competitor.name && competitor.domain);
  // Sentiment and Technical Foundation have no per-competitor input, so a
  // "competitor composite" would be computed on a different weight basis and
  // would not be comparable to the subject's.
  assert.equal(competitor.composite, undefined);
});

test('report evidence exposes cited domains and links, never quoted text', () => {
  const cited = spec.components.schemas.CitedDomainOut.properties;
  assert.ok(cited.domain && cited.citations && cited.sampleUrl);
  for (const forbidden of ['title', 'snippet', 'excerpt', 'text', 'quote']) {
    assert.equal(cited[forbidden], undefined, `CitedDomainOut.${forbidden} would quote a source`);
  }
});

test('no report schema exposes a prose field', () => {
  const forbidden = [
    'text', 'answer', 'response', 'snippet', 'excerpt', 'quote', 'body',
    'content', 'description', 'tagline', 'summary', 'narrative', 'rationale',
  ];
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    if (!name.startsWith('Report') && !['CitedDomainOut', 'MentionShareOut', 'EngineCoverageOut'].includes(name)) {
      continue;
    }
    for (const field of forbidden) {
      assert.equal(
        schema.properties?.[field], undefined,
        `${name}.${field} could render third-party prose`,
      );
    }
  }
});

test('report generation is a GET — it presents, it does not compute', () => {
  const operations = Object.keys(spec.paths['/api/v1/scans/{scanId}/report']);
  assert.deepEqual(operations, ['get']);
});

// --- action list (Epic 8) -------------------------------------------------

test('the fix generation endpoints are present', () => {
  const operations = Object.keys(spec.paths['/api/v1/scans/{scanId}/fixes']);
  // POST generates (it spends a model call); GET reads back.
  assert.deepEqual([...operations].sort(), ['get', 'post']);
});

test('an action item is keyed back to the candidate it enriches', () => {
  // The whole design: generated copy merges onto the client's derived list by
  // key. Without source + sourceKey the report cannot match them up.
  const props = Object.keys(spec.components.schemas.ActionItemOut.properties);
  assert.ok(props.includes('source'));
  assert.ok(props.includes('sourceKey'));
  assert.deepEqual([...spec.components.schemas.ActionItemSource.enum].sort(), ['audit', 'gap']);
});

test('an action item carries reasoned priority and effort', () => {
  // §7 Epic 8: "priority + effort estimation per fix".
  const props = Object.keys(spec.components.schemas.ActionItemOut.properties);
  assert.ok(props.includes('priority'));
  assert.ok(props.includes('effort'));
  assert.deepEqual([...spec.components.schemas.Priority.enum].sort(), ['high', 'low', 'medium']);
  assert.deepEqual([...spec.components.schemas.Effort.enum].sort(), ['L', 'M', 'S']);
});

test('pointsUpside stays a nullable string-encoded decimal', () => {
  // An audit fix has no measurable point value. Null, never zero, and never a
  // JSON number — same decimal convention as every other score on the wire.
  const prop = spec.components.schemas.ActionItemOut.properties.pointsUpside;
  const variants = prop.anyOf ?? [prop];
  assert.ok(variants.some((v) => v.type === 'null'));
  assert.ok(variants.some((v) => v.type === 'string'));
  assert.ok(!variants.some((v) => v.type === 'number'));
});

test('the generator records which model wrote the copy', () => {
  // prompt_sets.generated_by precedent: a change in wording quality must be
  // attributable to a model version.
  assert.ok('generatedBy' in spec.components.schemas.ActionItemOut.properties);
  assert.ok('generatedBy' in spec.components.schemas.ActionItemListOut.properties);
});

test('a failed generation is a status, not an empty list', () => {
  // "nothing to fix" and "generation failed" are different things to tell a
  // viewer, exactly as with score status vs a null composite.
  const props = Object.keys(spec.components.schemas.ActionItemListOut.properties);
  assert.ok(props.includes('status'));
  assert.ok(props.includes('reasonCode'));
});

test('the report carries the generated fix list', () => {
  assert.ok('actionItems' in spec.components.schemas.ReportOut.properties);
});

test('no action item schema exposes third-party prose', () => {
  // `title` and `detail` are ours (ip-safety.md #7, models/action_item.py).
  // Nothing sourced from a competitor, publisher or engine may sit beside them.
  const forbidden = [
    'text', 'answer', 'response', 'snippet', 'excerpt', 'quote', 'body',
    'content', 'html', 'raw', 'tagline', 'summary', 'positioning', 'about',
    'metaDescription', 'rationale', 'priorityReason', 'effortReason',
  ];
  for (const name of ['ActionItemOut', 'ActionItemListOut']) {
    for (const field of forbidden) {
      assert.equal(
        spec.components.schemas[name].properties?.[field], undefined,
        `${name}.${field} could render third-party prose`,
      );
    }
  }
});
