/**
 * Contract tests over the generated OpenAPI types.
 *
 * These guard the pipeline itself: that generation ran, that it covers the
 * endpoints the frontend depends on, and that the conventions fixed in
 * docs/api-contracts.md actually hold in the emitted schema. A drifted or
 * stale api.gen.ts fails here rather than in a browser.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const spec = JSON.parse(
  readFileSync(fileURLToPath(new URL('../openapi.json', import.meta.url)), 'utf8'),
);
const generated = readFileSync(
  fileURLToPath(new URL('../src/api.gen.ts', import.meta.url)),
  'utf8',
);

test('openapi.json is a 3.1 document', () => {
  assert.match(spec.openapi, /^3\.1/);
});

test('every endpoint is under the /api/v1 base path', () => {
  for (const path of Object.keys(spec.paths)) {
    assert.ok(path.startsWith('/api/v1'), `${path} is outside /api/v1`);
  }
});

test('paths use kebab-case segments', () => {
  for (const path of Object.keys(spec.paths)) {
    for (const segment of path.split('/').filter(Boolean)) {
      if (segment.startsWith('{')) continue;
      assert.ok(
        !/[A-Z_]/.test(segment),
        `path segment "${segment}" in ${path} is not kebab-case`,
      );
    }
  }
});

test('the endpoints the web app depends on are present', () => {
  for (const required of [
    '/api/v1/auth/sign-up',
    '/api/v1/auth/login',
    '/api/v1/auth/logout',
    '/api/v1/auth/me',
    '/api/v1/dashboard',
    '/api/v1/health',
  ]) {
    assert.ok(spec.paths[required], `missing endpoint ${required}`);
  }
});

test('response bodies are camelCase', () => {
  const props = Object.keys(spec.components.schemas.UserOut.properties);
  assert.ok(props.includes('fullName'));
  assert.ok(props.includes('lastLoginAt'));
  assert.ok(!props.some((p) => p.includes('_')), `snake_case leaked: ${props}`);
});

test('generation ran and produced the expected surface', () => {
  assert.match(generated, /auto-generated by openapi-typescript/);
  for (const name of ['UserOut', 'AgencyOut', 'MeOut', 'DashboardOut', 'SignUpRequest']) {
    assert.ok(generated.includes(name), `generated types missing ${name}`);
  }
});

test('no password field is ever returned in a response schema', () => {
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    if (!name.endsWith('Out')) continue;
    const props = Object.keys(schema.properties ?? {});
    assert.ok(
      !props.some((p) => /password|hash|secret/i.test(p)),
      `${name} exposes a credential field: ${props}`,
    );
  }
});

test('score fields are nullable so INSUFFICIENT_DATA is representable', () => {
  // scoring-spec.md: an unrunnable scan is null, never 0.
  const composite = spec.components.schemas.ScanSummaryOut.properties.compositeScore;
  const json = JSON.stringify(composite);
  assert.ok(json.includes('null'), `compositeScore is not nullable: ${json}`);
});

